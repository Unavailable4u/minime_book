#!/usr/bin/env python3
"""
refresh_atlas.py -- keep the MiniMe Atlas pages in sync with data/census.json.

The Atlas pages are static HTML. Their numbers, charts and tables used to be
typed in by a page builder that is not in this repo, so refreshing
data/census.json never changed what the site showed. This script is that
missing step: it re-renders every census-driven region of every census-driven
page from data/census.json, in place.

    python scripts/refresh_atlas.py                    # refresh pages + summary.md from data/census.json
    python scripts/refresh_atlas.py --check            # change nothing; exit 1 if anything is out of date
    python scripts/refresh_atlas.py --census-from ../MiniMe
                                                       # first regenerate data/census.json from a MiniMe
                                                       # checkout (its scripts/codebase_census.py), then refresh

Only the Python standard library is used.

What it refreshes (each regenerated byte-for-byte identically from the census it
was originally built from -- that is how every renderer below was validated):

    index      KPI cards, language pie, commits per month, code-by-area, largest files,
               most-changed files, most complex functions, snapshot line
    code       file table                      functions   function table
    history    KPIs, calendar, monthly lines, weekdays, biggest commits, latest commits
    map        treemap data                    agents      table, KPIs, provider and role charts
    api        route table, KPIs, routes per file
    infra      services, Dockerfiles, CI pipeline, dependencies, environment variables
    explore    file, function and route search data

What it deliberately does NOT touch, because the census cannot supply it:

    * Anything from the Graphify graph: the graph nodes/links and "guides" cards on index,
      "Graph hubs", "Frontend files that call the API most", and the per-route "frontend
      callers" column on api. Existing callers are carried over by (method, path); routes
      that are new since the last Graphify run show a blank.
      explore's connection edges are carried over too, remapped by file path.
    * Pages built from other inputs: tests and health (a pytest/coverage run and notes),
      data (Supabase schema), tables, graph, graph-viewer, roadmap, finance, decisions, ...
      They keep their own "Built ... from commit ..." label, so each page stays honest
      about how old it is.
"""
