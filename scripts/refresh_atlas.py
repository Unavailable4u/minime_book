#!/usr/bin/env python3
"""
refresh_atlas.py -- keep the MiniMe Atlas pages in sync with data/census.json.

The Atlas pages are static HTML. Their numbers, charts and tables used to be
typed in by a page builder that is not in this repo, so refreshing
data/census.json never changed what the site showed. This script is that
missing step: it re-renders every census-driven region of every census-driven
page from data/census.json, in place.

    python scripts/refresh_atlas.py                    # refresh pages + summary.md from data/census.json
    python scripts/refresh_atlas.py --check            # change nothing; exit 1 if anything is out of date
    python scripts/refresh_atlas.py --census-from ../MiniMe
                                                       # first regenerate data/census.json from a MiniMe
                                                       # checkout (its scripts/codebase_census.py), then refresh

Only the Python standard library is used.

What it refreshes (each regenerated byte-for-byte identically from the census it
was originally built from -- that is how every renderer below was validated).
code.html, functions.html and explore.html are not on this list any more (P19): they are thin pages that send the reader
to explorer.html, which reads the sharded data/code/ files listed below, so no table of files or functions is baked into HTML:

    history    KPIs, calendar, monthly lines, weekdays, biggest commits, latest commits
    map        treemap data
    data/code/routes.json   (P17) every route with handler, deps, response model and router, for api.html. The "callers" half (which
                            frontend files call a route) is written by refresh_graph.py; each script keeps the other's half.
    data/code/agents.json   (P17) agent modules, roles and provider key slots, for agents.html. api.html and agents.html are shells
                            that assets/js/api.js and agents.js draw from these two files.
    data/code/infra.json    (P18) compose services, Dockerfiles, CI jobs, dependency manifests and every environment variable read in
                            code, for infra.html (a shell that assets/js/infra.js draws). The data model page has its own script,
                            scripts/refresh_schema.py, which writes data/code/schema.json.
    data/index/stats.json   the live numbers the shared shell shows (sidebar counts, snapshot chip)
    data/index/vitals.json  the "census" half of the Overview's numbers (KPIs, languages, commits per month, areas,
                            largest / most-changed / most complex, docstring coverage, the directory table counts).
                            index.html itself is a shell now (P07): assets/js/overview.js draws it from this file.
                            refresh_graph.py writes the "graph" half of the same file; each script keeps the other's half.
    data/index/*.json       the command-palette search index (scripts/build_index.py: pages, book headings,
                            files, routes, functions). It follows the census, so it is rebuilt here too.
    data/code/              the sharded code data the Explorer reads (P10, scripts/build_code.py): tree.json, files/<shard>.json
                            (every file with its functions and classes), imports.json (resolved imports and who imports a
                            file) and callers/<shard>.json (who calls a function). It follows the census, so it is rebuilt here too.

What it deliberately does NOT touch, because the census cannot supply it:

    * Anything from the Graphify graph or the frontend scan: the "graph" half of data/index/vitals.json (nodes, links,
      communities, hubs) and the per-route "callers" in data/code/routes.json. Existing callers are carried over by
      route key (method + path); a route that is new since the last scan starts with none.
    * Pages built from other inputs: tests and health (a pytest/coverage run and notes),
      data (Supabase schema), tables, graph, graph-viewer, roadmap, finance, decisions, ...
      They keep their own "Built ... from commit ..." label, so each page stays honest
      about how old it is.
"""
