def refresh_explore(html, c):
    files = nonbinary(c)
    idx = {f["path"]: i for i, f in enumerate(files)}
    old_F, old_EG = read_literal(html, "const F="), read_literal(html, ",EG=")
    old_path = {i: r[0] for i, r in enumerate(old_F)}
    F = [[f["path"], f["lang"][:2], f["code"], len(G(f, "functions")), (f.get("git") or {}).get("commits", 0), (f.get("git") or {}).get("last") or "",
          1 if f.get("test") else 0, (f.get("module_doc") or "").strip().split("\n")[0][:90]] for f in files]
    FN = [[fn["name"], idx[f["path"]], fn["start"], fn["loc"], fn["kind"]] for f in files for fn in G(f, "functions")]
    RT = [[r["method"], r["path"], idx[r["file"]], r["handler"], r["line"]] for r in c["routes"]]
    # connection edges come from the Graphify graph: carry them over, re-indexed by file path
    remap = lambda i: idx.get(old_path.get(i, ""), None)
    EG = {}
    for k, v in old_EG.items():
        nk = remap(int(k))
        if nk is None:
            continue
        o = [[remap(t), w] for t, w in v["o"] if remap(t) is not None]
        i_ = [[remap(t), w] for t, w in v["i"] if remap(t) is not None]
        if o or i_:
            EG[str(nk)] = {"o": o, "i": i_}
    EG = {k: EG[k] for k in sorted(EG, key=int)}
    compact = lambda v: json.dumps(v, separators=(",", ":"))
    html = replace_literal(html, "const F=", compact(F))
    html = replace_literal(html, ",FN=", compact(FN))
    html = replace_literal(html, ",RT=", compact(RT))
    return replace_literal(html, ",EG=", compact(EG))


