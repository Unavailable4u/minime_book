def update_summary(text, c):
    nl = "\r\n" if "\r\n" in text else "\n"
    s = text.replace("\r\n", "\n")
    files = sum(1 for f in c["files"] if not f.get("binary"))
    s = sub_once(s, r"(?m)^Snapshot \d{4}-\d{2}-\d{2}, commit [0-9a-f]+\.$", f"Snapshot {c['meta']['generated'][:10]}, commit {c['git']['head']}.")
    s = sub_once(s, r"(?m)^- [\d,]+ files, [\d,]+ lines of code, [\d,]+ functions, \d+ API routes, \d+ commits\.$",
                 f"- {fmt(files)} files, {fmt(c['totals']['code'])} lines of code, {fmt(c['totals']['functions'])} functions, "
                 f"{len(c['routes'])} API routes, {len(c['git']['commits'])} commits.")
    return s.replace("\n", nl)


def refresh_all(root, census):
    """Return {path: new_text} for every file whose content would change."""
    changes = {}
    for name, fn in PAGES.items():
        path = root / f"{name}.html"
        old, crlf = read_lf(path)
        new = stamp(fn(old, census), census)
        if new != old:
            changes[path] = to_native(new, crlf)
    sp = root / "data" / "summary.md"
    if sp.exists():
        old, crlf = read_lf(sp)
        new = update_summary(old, census)
        if new != old:
            changes[sp] = to_native(new, crlf)
    return changes


def read_lf(path):
    """Read a text file as LF, remembering whether it used CRLF (Windows checkouts with autocrlf)."""
    raw = Path(path).read_bytes().decode("utf-8")
    return raw.replace("\r\n", "\n"), "\r\n" in raw


def to_native(text, crlf):
    return text.replace("\n", "\r\n") if crlf else text


def census_problems(c):
    """Reasons a freshly generated census should not replace a good one."""
    out = []
    if c["meta"].get("js_parser") != "tree-sitter":
        out.append("JavaScript was parsed with the heuristic fallback, so function counts would differ. Fix: pip install tree-sitter tree-sitter-javascript")
    if any("build" not in s for s in c.get("docker_compose", [])) or any("steps" not in j for w in c.get("ci", {}).values() for j in w.get("jobs", [])):
        out.append("docker-compose / CI files were parsed without PyYAML (details missing, volumes mistaken for services). Fix: pip install pyyaml")
    if c["git"].get("dirty_files"):
        out.append(f"the MiniMe checkout has {c['git']['dirty_files']} uncommitted or untracked file(s) (patch files left in the repo?), and the census scans the working copy. Fix: check `git status --short` in MiniMe")
    return out


def run_census(minime_repo, out, force=False):
    repo = Path(minime_repo).resolve()
    script = repo / "scripts" / "codebase_census.py"
    if not script.exists():
        sys.exit(f"{script} not found. --census-from must point at a MiniMe checkout.")
    tmp = out.with_name(out.name + ".tmp")
    try:
        subprocess.run([sys.executable, str(script), str(repo), str(tmp)], check=True)
        problems = census_problems(json.loads(tmp.read_text(encoding="utf-8")))
        if problems and not force:
            sys.exit("Not replacing data/census.json, the new census is not trustworthy:\n  - " + "\n  - ".join(problems)
                     + "\n(pass --force to use it anyway)")
        tmp.replace(out)
    finally:
        tmp.unlink(missing_ok=True)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", default=str(ROOT), help="the minime_book checkout (default: this repo)")
    ap.add_argument("--census-from", metavar="MINIME_REPO", help="regenerate data/census.json from this MiniMe checkout first")
    ap.add_argument("--force", action="store_true", help="with --census-from: accept a census even if validation finds problems")
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if any page or summary.md is out of date")
    args = ap.parse_args(argv)
    root = Path(args.root)
    cpath = root / "data" / "census.json"
    if args.census_from:
        if args.check:
            sys.exit("--census-from rewrites data/census.json, so it cannot be combined with --check")
        run_census(args.census_from, cpath, args.force)
    census = json.loads(cpath.read_text(encoding="utf-8"))
    changes = refresh_all(root, census)
    if args.check:
        for p in sorted(changes):
            print("out of date:", p.relative_to(root))
        print("everything is in sync with data/census.json" if not changes else f"{len(changes)} file(s) out of date; run: python scripts/refresh_atlas.py")
        return 1 if changes else 0
    for p, text in changes.items():
        p.write_bytes(text.encode("utf-8"))
        print("updated:", p.relative_to(root))
    if not changes:
        print("already up to date")
    g = census["git"]
    print(f"census: {census['meta']['generated'][:10]}, commit {g['head']}, parser {census['meta']['js_parser']}" + (f", WARNING: {g['dirty_files']} uncommitted file(s) when it was generated" if g["dirty_files"] else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
