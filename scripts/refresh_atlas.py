from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
G = lambda f, k: f.get(k) or []
fmt = lambda n: f"{n:,}"
esc = lambda s: _html.escape(s, quote=True)          # most pages escape quotes ...
esc_nq = lambda s: _html.escape(s, quote=False)      # ... infra does not


# ------------------------------------------------------------------ html helpers
def find_card(html, title):
    """(start, end) of the <div class="card"> whose <h3> begins with `title`, balancing nested divs."""
    m0 = re.search(r'<div class="card"[^>]*><h3>' + re.escape(title), html)
    if not m0:
        raise KeyError("card not found: " + title)
    return m0.start(), _div_end(html, m0.start())


def _div_end(html, start):
    depth = 0
    for m in re.finditer(r"<div\b|</div>", html[start:]):
        depth += 1 if m.group(0).startswith("<div") else -1
        if depth == 0:
            return start + m.end()
    raise ValueError("unbalanced <div>")


def replace_card(html, title, new):
    a, b = find_card(html, title)
    return html[:a] + new + html[b:]


def replace_first_grid(html, new):
    """The first KPI grid on a page: <div class="grid"><div class="card"><div class="k">..."""
    start = html.find('<div class="grid"><div class="card"><div class="k">')
    if start < 0:
        raise KeyError("KPI grid not found")
    return html[:start] + new + html[_div_end(html, start):]


def replace_literal(html, marker, new_literal):
    """Replace the JSON literal that follows `marker` (e.g. 'ROWS=' or 'const TREE=')."""
    i = html.find(marker)
    if i < 0:
        raise KeyError("data marker not found: " + marker)
    start = i + len(marker)
    _, end = json.JSONDecoder().raw_decode(html, start)
    return html[:start] + new_literal + html[end:]


def read_literal(html, marker):
    i = html.find(marker)
    if i < 0:
        raise KeyError("data marker not found: " + marker)
    val, _ = json.JSONDecoder().raw_decode(html, i + len(marker))
    return val


def sub_once(html, pattern, repl):
    html, n = re.subn(pattern, lambda m: repl(m) if callable(repl) else repl, html, count=1)
    if n != 1:
        raise ValueError("expected exactly one match for: " + pattern)
    return html


def built_label(c):
    return f"Built {c['meta']['generated'][:10]} from commit {c['git']['head']}."


def stamp(html, c):
    return sub_once(html, r"Built \d{4}-\d{2}-\d{2} from commit [0-9a-f]+\.", built_label(c))


def bar(title, text, value, mx, scale=55.0, floor=1.1):
    w = max(floor, round(value / mx * scale, 1))
    return f'<div class="bar"><span title="{esc(title)}">{esc(text)}</span><i style="width:{w:.1f}%"></i><em>{fmt(value)}</em></div>'


def bars(items):
    """items: [(label, value)] scaled to their own maximum."""
    mx = max((v for _, v in items), default=1) or 1
    return "".join(bar(t, t, v, mx) for t, v in items)


def bars_card(title, items):
    """items: [(title_attr, text, value)]"""
    mx = max((v for _, _, v in items), default=1) or 1
    return f'<div class="card"><h3>{title}</h3>' + "".join(bar(t, x, v, mx) for t, x, v in items) + "</div>"


def kpi_grid(vals):
    return '<div class="grid">' + "".join(f'<div class="card"><div class="k">{k}</div><div class="l">{l}</div></div>' for k, l in vals) + "</div>"


base = lambda p: p.rsplit("/", 1)[-1]
CODE_LANGS = ("python", "javascript")
PIE_EXCLUDE = {"html", "json", "markdown", "text", "other", "yaml", "toml"}
PIE_COLORS = ["#ff2052", "#a78bfa", "#f59e0b", "#34d399", "#f06cb4"]


def nonbinary(c):
    return sorted((f for f in c["files"] if not f.get("binary")), key=lambda f: f["path"])


# ------------------------------------------------------------------------- index
def index_kpis(c):
    F = c["files"]
    test = [f for f in F if f.get("test")]
    return {
        "files": sum(1 for f in F if not f.get("binary")),
        "total lines": c["totals"]["lines"],
        "lines of code": c["totals"]["code"],
        "functions & methods": c["totals"]["functions"],
        "API routes": len(c["routes"]),
        "commits": len(c["git"]["commits"]),
        "tests written": sum(1 for f in test for fn in G(f, "functions") if fn["name"].startswith("test")),
        "source files": sum(1 for f in F if not f.get("test") and f["lang"] in CODE_LANGS),
        "test files": sum(1 for f in test if f["lang"] in CODE_LANGS),
    }


def pie_card(c):
    cnt = collections.Counter()
    for f in c["files"]:
        if f.get("binary") or f["lang"] in PIE_EXCLUDE:
            continue
        cnt[f["lang"]] += f.get("code", 0)
    rows = [(l, v) for l, v in cnt.most_common() if v > 0]
    total = sum(v for _, v in rows) or 1
    cum, stops = 0, []
    for i, (l, v) in enumerate(rows):
        a = cum / total * 100
        cum += v
        stops.append(f"{PIE_COLORS[i % len(PIE_COLORS)]} {a:.1f}% {cum / total * 100:.1f}%")
    legend = "".join(f'<div><i style="background:{PIE_COLORS[i % len(PIE_COLORS)]}"></i>{esc(l)} <b>{fmt(v)}</b></div>' for i, (l, v) in enumerate(rows))
    return ('<div class="card"><h3>Code by language <span class="l" style="font-weight:400">(generated HTML, JSON and docs excluded)</span></h3>'
            f'<div class="row"><div class="pie" style="background:conic-gradient({",".join(stops)})"></div><div class="lg">{legend}</div></div></div>')


def commits_card(c):
    per = collections.Counter(x["date"][:7] for x in c["git"]["commits"])
    months = sorted(per)
    mx = max(per.values())
    parts = [f'<div class="card"><h3>Commits per month</h3><svg viewBox="0 0 {68 * len(months)} 104" width="100%" height="110">']
    for i, m in enumerate(months):
        v = per[m]
        h = max(4, round(v / mx * 58))
        x = 8 + 68 * i
        y = 86 - h
        cx = x + 26
        parts.append(f'<rect x="{x}" y="{y}" width="52" height="{h}" rx="4" fill="#ff2052"/>'
                     f'<text x="{cx}" y="101" font-size="13" fill="#a8a6a0" text-anchor="middle">{m[2:]}</text>'
                     f'<text x="{cx}" y="{y - 5}" font-size="13" fill="#f2f1ed" text-anchor="middle">{v}</text>')
    parts.append("</svg></div>")
    return "".join(parts)


def area_card(c):
    agg = collections.Counter()
    for f in c["files"]:
        if f.get("binary") or f["lang"] not in CODE_LANGS:
            continue
        agg["/".join(f["path"].split("/")[:-1][:2]) or "(root)"] += f.get("code", 0)
    return bars_card("Code lines by area", [(a, a, v) for a, v in agg.most_common(12)])


def largest_card(c):
    fs = sorted((f for f in c["files"] if f["lang"] in CODE_LANGS and not f.get("test")), key=lambda f: -f["code"])[:10]
    return bars_card("Largest files (code lines)", [(base(f["path"]), base(f["path"]), f["code"]) for f in fs])


def changed_card(c):
    fs = sorted((f for f in c["files"] if f.get("git") and f["lang"] in CODE_LANGS and not f.get("test")), key=lambda f: -f["git"]["commits"])[:10]
    return bars_card("Most-changed files (commits)", [(base(f["path"]), base(f["path"]), f["git"]["commits"]) for f in fs])


def complex_card(c):
    rows = sorted(((fn["cc_deep"], fn["name"], base(f["path"])) for f in c["files"] for fn in G(f, "functions")), key=lambda r: -r[0])
    return bars_card("Most complex functions", [(f"{n}  {b}", f"{n}  {b}", v) for v, n, b in rows[:10]])


def snapshot_sentence(c):
    n = c["git"]["dirty_files"]
    tail = "No uncommitted files at the time." if n == 0 else f"{n} uncommitted file{'s' if n != 1 else ''} at the time."
    return f"Snapshot of your working copy on {c['meta']['generated'][:10]}, branch {c['git']['branch']}. {tail}"


def refresh_index(html, c):
    for label, value in index_kpis(c).items():   # graph nodes / graph links / guides are not census data: left as they are
        pat = re.compile(r'(<div class="k">)[^<]*(</div><div class="l">' + re.escape(label) + r"</div>)")
        html, n = pat.subn(lambda m: m.group(1) + fmt(value) + m.group(2), html)
        if n != 1:
            raise ValueError(f"index KPI card {label!r}: expected 1 match, got {n}")
    for title, fn in (("Code by language", pie_card), ("Commits per month", commits_card), ("Code lines by area", area_card),
                      ("Largest files (code lines)", largest_card), ("Most-changed files (commits)", changed_card),
                      ("Most complex functions", complex_card)):
        html = replace_card(html, title, fn(c))
    return sub_once(html, r'(<p class="sub">)Snapshot of your working copy on [^<]*(</p>)', lambda m: m.group(1) + snapshot_sentence(c) + m.group(2))


# ----------------------------------------------------------------- code / functions
def file_rows(c):
    rows = []
    for f in nonbinary(c):
        g = f.get("git") or {}
        rows.append([f["path"], f["lang"], f["lines"], f["code"], len(G(f, "functions")), g.get("commits", 0), g.get("last") or "", "test" if f.get("test") else ""])
    return rows


def refresh_code(html, c):
    rows = file_rows(c)
    html = replace_literal(html, "ROWS=", json.dumps(rows))
    return sub_once(html, r"Every file in the repo \([\d,]+\)\.", f"Every file in the repo ({fmt(len(rows))}).")


def function_rows(c, n=4000):
    allf = [[fn["qual"], f["path"], fn["kind"], fn["loc"], fn["code"], fn["cc"], fn["cc_deep"], fn["args"], fn["start"]] for f in c["files"] for fn in G(f, "functions")]
    return sorted(allf, key=lambda r: (-r[3], r[1], r[8]))[:n], len(allf)


def refresh_functions(html, c):
    rows, total = function_rows(c)
    html = replace_literal(html, "ROWS=", json.dumps(rows))
    return sub_once(html, r"[\d,]+ functions, methods and components\. Showing the largest [\d,]+\.",
                    f"{fmt(total)} functions, methods and components. Showing the largest {fmt(len(rows))}.")


# ----------------------------------------------------------------------- history
def _hstats(c):
    cm = c["git"]["commits"]
    days = collections.Counter(x["date"] for x in cm)
    ds = [dt.date.fromisoformat(x["date"]) for x in cm]
    return cm, days, min(ds), max(ds)


def history_kpis(c):
    cm, days, d0, d1 = _hstats(c)
    return kpi_grid([(fmt(len(cm)), "commits"), (fmt(len(days)), "active days"), (f"{(d1 - d0).days} days", "span"),
                     (f"{len(cm) / len(days):.1f}", "commits per active day"),
                     (fmt(sum(x["added"] for x in cm)), "lines added, ever"), (fmt(sum(x["deleted"] for x in cm)), "lines removed, ever")])


def calendar_card(c):
    cm, days, d0, d1 = _hstats(c)
    start = d0 - dt.timedelta(days=d0.weekday())
    mx = max(days.values())
    nweeks = (d1 - start).days // 7 + 1
    out = [f'<svg viewBox="0 0 {34 + 17 * nweeks + 6} 140" width="100%">']
    for lab, y in (("Mon", 24), ("Wed", 58), ("Fri", 92)):
        out.append(f'<text x="0" y="{y}" font-size="10" fill="#a8a6a0">{lab}</text>')
    d, prev = start, start.month
    while d <= d1:
        w, wd = (d - start).days // 7, d.weekday()
        n = days.get(d.isoformat(), 0)
        fill, op = ("#1b1b22", 1.0) if n == 0 else ("#ff2052", 0.25 + 0.75 * n / mx)
        out.append(f'<rect x="{34 + 17 * w}" y="{12 + 17 * wd}" width="14" height="14" rx="3" fill="{fill}" fill-opacity="{op:.2f}"><title>{d.isoformat()}: {n} commits</title></rect>')
        if wd == 0:   # a month label sits after the Monday cell of the first week whose Monday is in a new month
            if w >= 1 and d.month != prev:
                out.append(f'<text x="{34 + 17 * w}" y="136" font-size="10" fill="#a8a6a0">{d.strftime("%b")}</text>')
            prev = d.month
        d += dt.timedelta(days=1)
    out.append("</svg>")
    return '<div class="card" style="margin-top:14px"><h3>Every day you committed</h3>' + "".join(out) + "</div>"


def history_cards(c):
    cm = c["git"]["commits"]
    add, rem = collections.Counter(), collections.Counter()
    for x in cm:
        add[x["date"][:7]] += x["added"]
        rem[x["date"][:7]] += x["deleted"]
    months = sorted(set(add) | set(rem))
    left = ('<div class="card"><h3>Lines added vs removed, by month</h3>'
            + bars([(f"{m} added", add[m]) for m in months]) + bars([(f"{m} removed", rem[m]) for m in months]) + "</div>")
    wd = collections.Counter(dt.date.fromisoformat(x["date"]).weekday() for x in cm)
    names = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    big = sorted(cm, key=lambda x: -(x["added"] + x["deleted"]))[:10]
    right = ('<div class="card"><h3>Busiest weekdays</h3>' + bars([(names[i], wd[i]) for i in range(7)])
             + "<h3>Biggest commits</h3>" + bars([(x["subject"][:44], x["added"] + x["deleted"]) for x in big]) + "</div>")
    return left, right


def latest_table(c):
    rows = ["<tr><th>Date</th><th>Hash</th><th>Message</th><th>Files</th><th>Added</th><th>Removed</th></tr>"]
    for x in c["git"]["commits"][:30]:
        rows.append(f'<tr><td>{x["date"]}</td><td><code>{x["hash"][:7]}</code></td><td>{esc(x["subject"][:100])}</td><td class="n">{x["files"]}</td>'
                    f'<td class="n pos">+{fmt(x["added"])}</td><td class="n neg">-{fmt(x["deleted"])}</td></tr>')
    return '<div class="tw"><table>' + "".join(rows) + "</table></div>"


def refresh_history(html, c):
    html = replace_first_grid(html, history_kpis(c))
    html = replace_card(html, "Every day you committed", calendar_card(c))
    left, right = history_cards(c)
    html = replace_card(html, "Lines added vs removed", left)
    html = replace_card(html, "Busiest weekdays", right)
    a = html.find('<div class="tw"><table><tr><th>Date</th>')
    if a < 0:
        raise KeyError("latest commits table not found")
    b = html.find("</table></div>", a) + len("</table></div>")
    return html[:a] + latest_table(c) + html[b:]


# --------------------------------------------------------------------------- map
def map_tree(c):
    root = {}
    for f in c["files"]:
        if f.get("binary") or f["lang"] not in CODE_LANGS or f["code"] < 2:
            continue
        node, parts = root, f["path"].split("/")
        for d in parts[:-1]:
            node = node.setdefault(d, {})
        g = f.get("git") or {}
        node[parts[-1]] = ("leaf", {"n": parts[-1], "v": f["code"], "p": f["path"], "l": f["lang"][:2], "f": len(G(f, "functions")),
                                    "k": g.get("commits", 0), "d": g.get("last") or "", "t": 1 if f.get("test") else 0})

    def conv(name, node):
        kids = [v[1] if isinstance(v, tuple) else conv(k, v) for k, v in node.items()]
        while len(kids) == 1 and "c" in kids[0]:   # collapse chains of single-child folders: a/b
            name, kids = name + "/" + kids[0]["n"], kids[0]["c"]
        kids.sort(key=lambda k: -k["v"])
        return {"n": name, "c": kids, "v": sum(k["v"] for k in kids)}
    return conv(c["meta"]["root_name"], root)


def refresh_map(html, c):
    return replace_literal(html, "const TREE=", json.dumps(map_tree(c), separators=(",", ":")))


# --------------------------------------------------------------------------- api
def _short_api(p):
    return p.split("backend/api/", 1)[1] if p.startswith("backend/api/") else p


def refresh_api(html, c):
    old = read_literal(html, "ROWS=")
    callers = {(r[0], r[1]): r[7] for r in old}   # from the last Graphify run; not derivable from the census
    rows = [[r["method"], r["path"], r["handler"], _short_api(r["file"]), r["line"], ", ".join(r["deps"]) if r["deps"] else "none",
             r.get("response_model") or "", callers.get((r["method"], r["path"]), "")] for r in c["routes"]]
    html = replace_literal(html, "ROWS=", json.dumps(rows))
    cnt = collections.Counter(r["method"] for r in c["routes"])
    html = replace_first_grid(html, kpi_grid([
        (fmt(len(c["routes"])), "routes"), (fmt(cnt["GET"]), "GET"), (fmt(cnt["POST"]), "POST"), (fmt(cnt["PUT"] + cnt["PATCH"]), "PUT / PATCH"),
        (fmt(cnt["DELETE"]), "DELETE"), (fmt(sum(1 for r in c["routes"] if r["deps"])), "with declared auth/deps"),
        (fmt(sum(1 for r in rows if isinstance(r[7], int) and r[7] > 0)), "called by the frontend")]))
    stem = lambda p: p.rsplit("/", 1)[-1].rsplit(".", 1)[0]
    rpf = collections.Counter(stem(r["file"]) for r in c["routes"]).most_common(13)
    return replace_card(html, "Routes per file", '<div class="card"><h3>Routes per file</h3>' + bars(rpf) + "</div>")


# ------------------------------------------------------------------------ agents
def agent_rows(c):
    tests = [f for f in c["files"] if f.get("test")]
    out = []
    for f in sorted(c["files"], key=lambda f: f["path"]):
        p = f["path"]
        if not (p.startswith("backend/agents/") and p.endswith(".py")) or p.endswith("__init__.py") or f.get("test"):
            continue
        name = base(p)[:-3]
        g = f.get("git") or {}
        doc = (f.get("module_doc") or "").strip().split("\n")[0]
        pre = f"agents/{name}.py"
        if doc.startswith(pre):
            doc = doc[len(pre):].lstrip(" —-:").strip()
        out.append([name, doc[:52], f["code"], len(G(f, "functions")), sum(1 for t in tests if name in base(t["path"])), g.get("commits", 0), g.get("last") or ""])
    return out


def _role_serve(c):
    serve = collections.Counter()
    for v in c["registry"]["agent_capabilities"].values():
        for r in v["natural_roles"]:
            serve[r] += 1
    return serve


def refresh_agents(html, c):
    rows = agent_rows(c)
    reg = c["registry"]
    caps, roles, serve = reg["agent_capabilities"], reg["role_prompts_seed_keys"], _role_serve(c)
    html = replace_literal(html, "ROWS=", json.dumps(rows))
    html = replace_first_grid(html, kpi_grid([
        (fmt(len(rows)), "agent modules"), (fmt(len(roles)), "roles"), (fmt(len(caps)), "provider key slots"),
        (fmt(len({v["provider"] for v in caps.values()})), "providers"), (fmt(sum(r[2] for r in rows)), "agent code lines"),
        (fmt(sum(1 for r in rows if r[4] == 0)), "agents with no test file")]))
    prov = collections.Counter(v["provider"] for v in caps.values())
    html = replace_card(html, "Key slots per provider", '<div class="card"><h3>Key slots per provider</h3>' + bars(prov.most_common())
                        + '<p class="note" style="font-size:12.5px;color:#a8a6a0">Each slot is one API key in AGENT_CAPABILITIES (names only, no secrets).</p></div>')
    html = replace_card(html, "How many key slots can serve each role",
                        '<div class="card"><h3>How many key slots can serve each role</h3>' + bars([(r, serve[r]) for r in roles if serve[r] > 0]) + "</div>")
    pills = "".join(f'<span class="pill">{esc(r)}{"" if serve[r] > 0 else " · no key slot"}</span>' for r in roles)
    return replace_card(html, "All ", f'<div class="card" style="margin-top:14px"><h3>All {len(roles)} roles</h3>{pills}</div>')


# ------------------------------------------------------------------------- infra
def infra_services(c):
    cards = []
    for s in c["docker_compose"]:
        built = "Built from its Dockerfile" if s.get("build") else (f"Image {esc_nq(s['image'])}" if s.get("image") else "")
        pills = "".join(f'<span class="pill">port {esc_nq(p)}</span>' for p in s.get("ports", []))
        pills += "".join(f'<span class="pill">needs {esc_nq(d)}</span>' for d in s.get("depends_on", []))
        pills += "".join(f'<span class="pill">{esc_nq(e)}</span>' for e in s.get("env_names", []))
        cards.append(f'<div class="card"><h3 style="margin-top:0">{esc_nq(s["name"])}</h3><p class="l">{built}</p>{pills}</div>')
    for name, d in c["dockerfiles"].items():
        pills = "".join(f'<span class="pill">{esc_nq(x)}</span>' for x in d.get("from", []))
        port = (d["expose"][0] if d.get("expose") else "").strip()
        cmd = (d["cmd"][0] if d.get("cmd") else "").strip()
        cards.append(f'<div class="card"><h3 style="margin-top:0">{esc_nq(name)}</h3>{pills}<p class="l" style="margin:8px 0 0">Port {esc_nq(port)} · starts with <code>{esc_nq(cmd)}</code></p></div>')
    return '<h2>Services</h2><div class="grid g2">' + "".join(cards) + "</div>"


def infra_ci(c):
    cards = []
    for wf in c["ci"].values():
        for j in wf["jobs"]:
            steps = "".join(f'<li>{esc_nq(re.sub(r"@[0-9a-f]{40}$", "", st)[:70])}</li>' for st in j.get("steps", []))
            cards.append(f'<div class="card"><h3 style="margin-top:0">{esc_nq(j.get("name") or j["id"])}</h3><ol class="l" style="margin:0;padding-left:18px;font-size:12.5px">{steps}</ol></div>')
    return '<h2>CI pipeline</h2><div class="grid">' + "".join(cards) + "</div>"


def infra_deps(c):
    d = c["dependencies"]
    back, front, daemon = d["backend/requirements.txt"], d["frontend/package.json"], d["daemon/requirements.txt"]
    pill = lambda n, s: f'<span class=pill>{esc_nq(n)} <span style=color:#6d6b66>{esc_nq(s[:12])}</span></span>'
    qpill = lambda n, s: f'<span class="pill">{esc_nq(n)} <span style="color:#6d6b66">{esc_nq(s[:12])}</span></span>'
    left = f'<div class="card"><h3 style="margin-top:0">Backend ({len(back)})</h3>' + "".join(pill(x["name"], x["spec"]) for x in back) + "</div>"
    right = ('<div class="card"><h3 style="margin-top:0">Frontend</h3>' + "".join(qpill(k, v) for k, v in front["dependencies"].items())
             + "<h3>Dev tools</h3>" + "".join(qpill(k, v) for k, v in front.get("devDependencies", {}).items())
             + f"<h3>Daemon ({len(daemon)})</h3>" + "".join(f'<span class=pill>{esc_nq(x["name"])}</span>' for x in daemon) + "</div>")
    return '<h2>Dependencies</h2><div class="grid g2">' + left + right + "</div>"


def env_rows(c):
    examples = {e["name"] for v in c["env_examples"].values() for e in v}
    rows = []
    for name, files in c["env_usage"].items():
        first = files[0]
        rows.append([name, len(files), first.replace("backend/", "", 1) if first.startswith("backend/") else first, "yes" if name in examples else "no"])
    rows.sort(key=lambda r: -r[1])   # stable: ties keep the census's own order
    return rows


def _between(html, a, b, new):
    i = html.find(a)
    j = html.find(b, i)
    if i < 0 or j < 0:
        raise KeyError(f"section {a!r}..{b!r} not found")
    tail = "\n" if html[j - 1:j] == "\n" else ""
    return html[:i] + new + tail + html[j:]


def refresh_infra(html, c):
    html = _between(html, "<h2>Services</h2>", "<h2>CI pipeline</h2>", infra_services(c))
    html = _between(html, "<h2>CI pipeline</h2>", "<h2>Dependencies</h2>", infra_ci(c))
    html = _between(html, "<h2>Dependencies</h2>", "<h2>Environment variables", infra_deps(c))
    rows = env_rows(c)
    html = replace_literal(html, "ROWS=", json.dumps(rows))
    return sub_once(html, r"Environment variables used in code \([\d,]+\)", f"Environment variables used in code ({fmt(len(rows))})")


