def refresh_all(root, census):
    """Return {path: new_text} for every file whose content would change."""
    changes = {}
    for name, fn in PAGES.items():
        path = root / f"{name}.html"
        old, crlf = read_lf(path)
        new = stamp(fn(old, census), census)
        if new != old:
            changes[path] = to_native(new, crlf)
    sp = root / "data" / "summary.md"
    if sp.exists():
        old, crlf = read_lf(sp)
        new = update_summary(old, census)
        if new != old:
            changes[sp] = to_native(new, crlf)
    stp = root / STATS_REL
    new = json.dumps(build_stats(census), indent=2, sort_keys=True) + "\n"
    old, crlf = read_lf(stp) if stp.exists() else (None, False)
    if new != old:
        changes[stp] = to_native(new, crlf)
    for rel, new in ((ROUTES_REL, json_text(build_routes(census, read_json(root, ROUTES_REL)))), (AGENTS_REL, json_text(build_agents(census))), (INFRA_REL, json_text(build_infra(census)))):
        p = root / rel                                                 # P17 / P18: what api.html, agents.html and infra.html draw
        old, crlf = read_lf(p) if p.exists() else (None, False)
        if new != old:
            changes[p] = to_native(new, crlf)
    vp = root / VITALS_REL
    new = vitals_text(read_vitals(root), census=census_vitals(census, load_subsystems(root), load_topology(root)))
    old, crlf = read_lf(vp) if vp.exists() else (None, False)
    if new != old:
        changes[vp] = to_native(new, crlf)
    return changes


