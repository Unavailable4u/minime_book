def check_figures(root, files, ids_of, add):
    """Validates content/figures/*.json and every SVG under content/figures/. Reports through add(level, code, file, detail, message)."""
    root = Path(root)
    manifests = sorted(f for f in files if f.startswith(FIGURES_DIR) and f.endswith(".json") and "/" not in f[len(FIGURES_DIR):])
    svgs = sorted(f for f in files if f.startswith(FIGURES_DIR) and f.endswith(".svg"))

    for rel in svgs:                                   # a bad file is an error even when no manifest uses it yet
        try:
            text = (root / rel).read_bytes().decode("utf-8-sig")
        except (OSError, UnicodeDecodeError) as e:
            add("ERROR", "figure-bad-svg", rel, "-", f"cannot read as UTF-8: {e}")
            continue
        why = svg_problem(text) or svg_not_well_formed(text)
        if why:
            add("ERROR", "figure-bad-svg", rel, "-", f"SVG {why}" if svg_problem(text) else f"SVG is not well-formed: {why}")

    if not manifests:
        return
    nav = _read_json(root, NAV_PATH) if (root / NAV_PATH).is_file() else None
    chapters = {}                                      # chapter id -> url (nav items that have a "chapter" number)
    if isinstance(nav, dict):
        for w in nav.get("wings") or []:
            for it in (w.get("items") or []) if isinstance(w, dict) else []:
                if isinstance(it, dict) and it.get("id") and it.get("chapter") is not None and isinstance(it.get("url"), str):
                    chapters[it["id"]] = it["url"].split("#", 1)[0]

    for rel in manifests:
        stem = rel[len(FIGURES_DIR):-len(".json")]
        url = chapters.get(stem)
        if not url:
            add("ERROR", "figure-bad-manifest", rel, "-", f'"{stem}" is not a chapter id in {NAV_PATH}; a manifest is named <chapter id>.json')
            continue
        try:
            raw = json.loads((root / rel).read_bytes().decode("utf-8-sig"))
        except (OSError, ValueError):
            continue                                   # reported as bad-json
        items = raw if isinstance(raw, list) else raw.get("figures") if isinstance(raw, dict) else None
        if not isinstance(items, list):
            add("ERROR", "figure-bad-manifest", rel, "-", 'expected {"figures": [...]} (or a bare list)')
            continue
        if url not in files:
            continue                                   # nav-dead-url reports it
        scan = _HeadingIds()
        scan.feed((root / url).read_text(encoding="utf-8", errors="replace"))
        page_ids = ids_of(url)
        seen = set()
        for i, f in enumerate(items):
            fid = f.get("id") if isinstance(f, dict) else None
            at = fid if isinstance(fid, str) and fid else f"#{i}"

            def bad(code, why, key=None, level="ERROR"):
                add(level, code, rel, f"{at}|{key}" if key else at, f'figure "{at}": {why}')

            if not isinstance(f, dict):
                bad("figure-bad-entry", "is not an object")
                continue
            if not isinstance(fid, str) or not FIG_ID.match(fid):
                bad("figure-bad-entry", 'needs an "id" of lower-case letters, digits and hyphens')
                continue
            if fid in seen:
                bad("figure-bad-entry", "duplicate id")
                continue
            seen.add(fid)
            ftype = f.get("type")
            if ftype in FIG_RESERVED:
                bad("figure-bad-entry", f'type "{ftype}" is not available yet (a later patch)')
                continue
            if ftype not in FIG_TYPES:
                bad("figure-bad-entry", f'unknown type "{ftype}" (use {", ".join(FIG_TYPES)})')
                continue
            if not _fig_str(f.get("after")):
                bad("figure-bad-heading", 'needs "after" (the id of a heading; python scripts/list_headings.py <chapter> lists them)')
            elif f["after"].strip() not in scan.ids:
                bad("figure-bad-heading", f'"after" is "{f["after"]}", which is not an h1-h4 id in {url}')
            if not _fig_str(f.get("caption")):
                bad("figure-bad-entry", 'needs a "caption"', "caption")
            if not _fig_str(f.get("alt")):
                bad("figure-no-alt", 'needs an "alt": what the figure shows, for screen readers')
            if "place" in f and f["place"] not in ("start", "end"):
                bad("figure-bad-entry", '"place" must be "start" or "end"', "place")
            if "wide" in f and not isinstance(f["wide"], bool):
                bad("figure-bad-entry", '"wide" must be true or false', "wide")
            if f"fig-{fid}" in page_ids:
                bad("figure-bad-entry", f"the anchor fig-{fid} is already used in {url}", "anchor")

            src = f.get("src")
            if ftype == "arch":                          # P26: a generated architecture view, drawn inline
                reg = _read_json(root, ARCH_REGISTRY) if ARCH_REGISTRY in files else None
                views = {v.get("id") for v in (reg or {}).get("views", []) if isinstance(v, dict)}
                flows = {x.get("id") for x in (reg or {}).get("flows", []) if isinstance(x, dict)}
                view, flow = f.get("view"), f.get("flow")
                if not (isinstance(view, str) and FIG_ID.match(view)):
                    bad("figure-bad-entry", 'needs "view": the id of a view of content/arch-flows.json', "view")
                elif reg is not None and view not in views:
                    bad("figure-bad-src", f'view "{view}" is not a view of {ARCH_REGISTRY}', "view")
                if flow is not None:
                    if not (isinstance(flow, str) and FIG_ID.match(flow)):
                        bad("figure-bad-entry", '"flow" must be a flow id', "flow")
                    elif reg is not None and flow not in flows:
                        bad("figure-bad-src", f'flow "{flow}" is not a flow of {ARCH_REGISTRY}', "flow")
                if f.get("focus") is not None and not _fig_str(f.get("focus")):
                    bad("figure-bad-entry", '"focus" must be text', "focus")
                continue
            if ftype == "graph-slice":                   # P20: the graph neighbourhood of one file or folder
                focus, limit = f.get("focus"), f.get("limit")
                if not _fig_str(focus):
                    bad("figure-bad-entry", 'needs "focus": a file or folder path from data/index/paths.json', "focus")
                elif not FIG_SLICE_FOCUS.match(focus.strip()) or any(seg in (".", "..") for seg in focus.strip().split("/")):
                    bad("figure-bad-entry", '"focus" must be a repo-relative path of letters, digits and . _ @ + - separated by /, with no . or .. segment', "focus")
                else:
                    known = _repo_paths(root, files)
                    want = focus.strip().strip("/")
                    if known is not None and want not in known and not any(p.startswith(want + "/") for p in known):
                        bad("figure-bad-src", f'"focus" is "{want}", which is neither a file nor a folder of data/index/paths.json', "focus")
                if limit is not None and (isinstance(limit, bool) or not isinstance(limit, int) or not FIG_SLICE_MIN <= limit <= FIG_SLICE_MAX):
                    bad("figure-bad-entry", f'"limit" must be a whole number from {FIG_SLICE_MIN} to {FIG_SLICE_MAX}', "limit")
                continue
            if ftype == "archify":
                if not (_fig_str(src) and FIG_ARCHIFY_SRC.match(src)):
                    bad("figure-bad-src", 'needs "src": "architecture/<name>.html"', "src")
                elif src not in files:
                    bad("figure-bad-src", f"{src} does not exist", "src")
                size = f.get("size")
                if not (isinstance(size, list) and len(size) == 2 and all(isinstance(n, (int, float)) and not isinstance(n, bool) and 100 <= n <= 20000 for n in size)):
                    bad("figure-bad-entry", 'needs "size": [width, height], the pixel size of the diagram\'s SVG (100 to 20000)', "size")
                continue

            code = f.get("code")
            has_src, has_code = _fig_str(src), _fig_str(code)
            if has_src == has_code:
                bad("figure-bad-entry", 'needs exactly one of "src" or "code"', "source")
            ext = ".svg" if ftype == "svg" else ".mmd"
            if has_src and not has_code:
                if not (FIG_CONTENT_SRC.match(src) and src.endswith(ext)):
                    bad("figure-bad-src", f'"src" must be content/figures/...{ext}', "src")
                elif src not in files:
                    bad("figure-bad-src", f"{src} does not exist", "src")
            if has_code and not has_src and ftype == "svg":
                why = svg_problem(code) or svg_not_well_formed(code)
                if why:
                    bad("figure-bad-svg", f'inline "code" {why}' if svg_problem(code) else f'inline "code" is not well-formed: {why}', "code")
            if ftype == "mermaid" and MERMAID_VENDOR not in files:
                bad("figure-bad-src", f"a mermaid figure needs {MERMAID_VENDOR}; run: python scripts/vendor_mermaid.py", "vendor")


# ------------------------------------------------------------- architecture model (P25)
ARCH_REGISTRY = "content/arch-flows.json"
ARCH_LAYOUT = "content/arch-layout.json"
ARCH_DATA = "data/arch/"
ARCH_ATTR = re.compile(r"""data-arch-(view|flow)\s*=\s*["']([^"']*)["']""")


def _arch_evidence_paths(node):
    """Every evidence "path" cited anywhere in a flow (steps or lifecycle transitions)."""
    out = []
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "evidence" and isinstance(v, list):
                out += [e["path"] for e in v if isinstance(e, dict) and isinstance(e.get("path"), str)]
            else:
                out += _arch_evidence_paths(v)
    elif isinstance(node, list):
        for v in node:
            out += _arch_evidence_paths(v)
    return out


def check_arch(root, files, ids_of, add):
    """The architecture model (scripts/arch.py). Rules for the registry and layout come from arch.py itself; this adds the
    cross-file ones: a view needs its shard and a model entry, a flow cites only files of the repo (data/index/paths.json),
    and a page may only name views and flows that exist. A site without arch files passes."""
    root = Path(root)
    if ARCH_REGISTRY not in files and ARCH_LAYOUT not in files:
        return
    try:
        import importlib.util
        spec = importlib.util.spec_from_file_location("arch_for_check_site", Path(__file__).resolve().parent / "arch.py")
        arch = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(arch)
    except Exception as e:                              # arch.py missing or broken: say so once, skip the rest
        add("ERROR", "arch-bad-registry", ARCH_REGISTRY, "-", f"scripts/arch.py cannot be loaded: {e}")
        return
    reg = arch.load_registry(root)
    for msg in arch.registry_problems(reg, root):
        add("ERROR", "arch-bad-registry", ARCH_REGISTRY, "-", msg)
    if ARCH_LAYOUT in files:
        layout = _read_json(root, ARCH_LAYOUT)
        for msg in arch.layout_problems(layout if isinstance(layout, dict) else {}):
            add("ERROR", "arch-bad-layout", ARCH_LAYOUT, "-", msg)
    view_ids = {v["id"] for v in reg["views"]}
    flow_ids = {f["id"] for f in reg["flows"]}

    model = _read_json(root, ARCH_DATA + "model.json") if ARCH_DATA + "model.json" in files else None
    model_views = model.get("views") if isinstance(model, dict) else None
    for vid in sorted(view_ids):
        if f"{ARCH_DATA}views/{vid}.json" not in files:
            add("ERROR", "arch-missing-data", f"{ARCH_DATA}views/{vid}.json", vid, f'view "{vid}" has no shard; run: python scripts/arch.py build')
        if isinstance(model_views, (list, dict)) and vid not in {(x.get("id") if isinstance(x, dict) else x) for x in model_views} | (set(model_views) if isinstance(model_views, dict) else set()):
            add("ERROR", "arch-missing-data", ARCH_DATA + "model.json", vid, f'view "{vid}" is not in model.json; run: python scripts/arch.py build')

    paths_doc = _read_json(root, "data/index/paths.json") if "data/index/paths.json" in files else None
    known = set(paths_doc.get("paths", [])) if isinstance(paths_doc, dict) else None
    for rel in sorted(f for f in files if f.startswith(ARCH_DATA + "flows/") and f.endswith(".json")):
        flow = _read_json(root, rel)
        if flow is None:
            continue                                    # reported as bad-json
        if known is None:
            continue
        for path in sorted(set(_arch_evidence_paths(flow))):
            if path not in known:
                add("ERROR", "arch-bad-evidence", rel, path, f"cites {path}, which is not a file in data/index/paths.json")

    for rel in sorted(f for f in files if f.endswith(".html") and (root / f).is_file()):
        if rel.startswith("architecture/"):
            continue                                    # generated diagrams carry their own markup
        try:
            text = (root / rel).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for kind, ref in sorted(set(ARCH_ATTR.findall(text))):
            ok = ref in (view_ids if kind == "view" else flow_ids)
            if not ok:
                add("ERROR", "arch-bad-ref", rel, f"{kind}:{ref}", f'data-arch-{kind}="{ref}" is not a {kind} of {ARCH_REGISTRY}')


def dynamic_anchors(root, files):
    """{page: ids} of anchors that JavaScript draws, so a link to them is not a broken anchor (P23).
    architecture.html draws one section per view of data/arch/model.json (id = the view id) plus anatomy, modules and legacy."""
    out = {}
    model = _read_json(root, "data/arch/model.json") if "data/arch/model.json" in files else None
    views = model.get("views") if isinstance(model, dict) else None
    if isinstance(views, list) and "architecture.html" in files:
        out["architecture.html"] = {v["id"] for v in views if isinstance(v, dict) and isinstance(v.get("id"), str)} | set(STATIC_ARCH_ANCHORS)
    return out


def check_arch_legacy(root, files, add):
    """content/arch-legacy.json against architecture/*.html and data/arch/model.json (see the docstring: arch-legacy-bad)."""
    if ARCH_LEGACY not in files:
        return
    root = Path(root)
    reg = _read_json(root, ARCH_LEGACY)

    def bad(detail, msg):
        add("ERROR", "arch-legacy-bad", ARCH_LEGACY, detail, msg)

    if not isinstance(reg, dict) or not isinstance(reg.get("pages"), list) or not isinstance(reg.get("retired"), list):
        bad("-", 'expected {"pages": [...], "retired": [...]}')
        return
    model = _read_json(root, "data/arch/model.json")
    view_ids = {v.get("id") for v in model.get("views", []) if isinstance(v, dict)} if isinstance(model, dict) else None
    listed = set()
    for kind in ("pages", "retired"):
        for i, e in enumerate(reg[kind]):
            if not (isinstance(e, dict) and all(isinstance(e.get(k), str) and e.get(k) for k in ("file", "title", "view"))):
                bad(f"{kind}#{i}", f'{kind}[{i}] needs a "file", a "title" and a "view"')
                continue
            f, v = e["file"], e["view"]
            if f in listed:
                bad(f, f"{f} is listed twice")
            listed.add(f)
            if f not in files:
                bad(f, f"{f} does not exist")
                continue
            if view_ids is not None and v not in view_ids:
                bad(f"{f}|{v}", f'{f}: view "{v}" is not in data/arch/model.json')
            try:
                text = (root / f).read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            size = (root / f).stat().st_size
            is_redirect = f"../architecture.html#{v}" in text and size < LEGACY_REDIRECT_MAX
            if kind == "retired" and not is_redirect:
                bad(f, f'{f} is "retired" but is not the redirect page to ../architecture.html#{v} (under {LEGACY_REDIRECT_MAX // 1024} KB); run scripts/retire_legacy.py --apply')
            if kind == "pages" and size < LEGACY_REDIRECT_MAX:
                bad(f, f'{f} is listed as a real diagram but is only {size} bytes; move it to "retired"')
    for f in sorted(x for x in files if x.startswith("architecture/") and x.endswith(".html")):
        if f not in listed:
            bad(f, f"{f} is not listed in {ARCH_LEGACY}")


# ------------------------------------------------------------------ P23: budgets, lazy vendors, accessibility of the markup
CONTROL_TYPES_NO_LABEL = {"hidden", "submit", "button", "reset", "image"}


class A11yScan(HTMLParser):
    """Looks only at the markup in the file (not at what scripts draw). Findings are (code, line, detail, message)."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.lang, self.has_main, self.items = None, False, []
        self.ids, self.label_for, self.controls = {}, set(), []
        self._label, self._tpl, self._btn = 0, 0, None

    def _pos(self):
        return self.getpos()[0]

    def handle_starttag(self, tag, attrs):
        a = {k: (v if v is not None else "") for k, v in attrs}
        if tag == "template":
            self._tpl += 1
        if self._tpl:
            return
        if tag == "html":
            self.lang = a.get("lang", "").strip()
        if tag == "main" or a.get("role") == "main":
            self.has_main = True
        i = a.get("id", "").strip()
        if i and tag not in ("style", "script", "link", "meta") and not DYNAMIC.search(i):     # builders repeat <style id=...>; it is not rendered
            self.ids[i] = self.ids.get(i, 0) + 1
        t = a.get("tabindex", "").strip()
        if t.lstrip("+").isdigit() and int(t) > 0:
            self.items.append(("a11y-tabindex", self._pos(), f"tabindex={t}", f'tabindex="{t}" puts this element ahead of the natural order; use 0 or -1'))
        if tag == "img" and "alt" not in a:
            self.items.append(("a11y-img-alt", self._pos(), a.get("src", "-"), f'<img src="{a.get("src", "")}"> has no alt (use alt="" if it is decoration)'))
        if tag == "label":
            self._label += 1
            if a.get("for"):
                self.label_for.add(a["for"])
        named = bool(a.get("aria-label", "").strip() or a.get("aria-labelledby", "").strip() or a.get("title", "").strip())
        if tag in ("input", "select", "textarea"):
            if tag == "input" and a.get("type", "text").lower() in CONTROL_TYPES_NO_LABEL:
                return
            if a.get("aria-hidden") == "true" or "hidden" in a:
                return
            if not (named or self._label):
                self.controls.append((self._pos(), tag, a.get("id", ""), a.get("name", "") or a.get("type", "")))
        if tag == "button" and not named:
            self._btn = [self._pos(), ""]
        elif self._btn is not None and (a.get("alt", "").strip() or a.get("aria-label", "").strip()):
            self._btn[1] += "x"                                   # an <img alt> or an aria-labelled icon inside names the button

    def handle_endtag(self, tag):
        if tag == "template" and self._tpl:
            self._tpl -= 1
            return
        if self._tpl:
            return
        if tag == "label" and self._label:
            self._label -= 1
        if tag == "button" and self._btn is not None:
            line, text = self._btn
            self._btn = None
            if not text.strip():
                self.items.append(("a11y-button-name", line, f"line {line}", "a <button> with no text, aria-label or title"))

    def handle_data(self, data):
        if self._btn is not None and not self._tpl:
            self._btn[1] += data.strip()


def check_quality(root, files, page_rels, add, page_kb=PAGE_BUDGET_KB, chapter_kb=CHAPTER_BUDGET_KB, max_page_kb=MAX_PAGE_KB):
    """P23: size budgets for HTML, lazy vendor loading, and the accessibility of the static markup."""
    root = Path(root)
    for rel in (f for f in files if f.endswith(".html")):
        kb = (root / rel).stat().st_size / 1024
        name = rel.rsplit("/", 1)[-1]
        if kb > max_page_kb:
            add("ERROR", "page-too-big", rel, "-", f"{kb:.0f} KB of HTML (no page may be over {max_page_kb} KB)")
        elif rel in page_rels and name.startswith("doc-"):
            if kb > chapter_kb:
                add("WARN", "chapter-budget", rel, "-", f"{kb:.0f} KB (chapter budget {chapter_kb} KB)")
        elif rel in page_rels and kb > page_kb:
            add("ERROR", "page-budget", rel, "-", f"{kb:.0f} KB of HTML (budget {page_kb} KB for a page that is not a chapter): move the data into JSON that the page fetches")
    for rel in page_rels:
        try:
            text = (root / rel).read_bytes().decode("utf-8-sig")
        except (OSError, UnicodeDecodeError):
            continue
        scan = A11yScan()
        scan.feed(text)
        scan.close()
        if not scan.lang:
            add("ERROR", "a11y-lang", rel, "-", '<html> has no lang attribute (screen readers pick the voice from it)')
        if not scan.has_main:
            add("ERROR", "a11y-no-main", rel, "-", "no <main> landmark: the skip link and screen-reader navigation have nothing to land on")
        for code, line, detail, msg in scan.items:
            add("ERROR", code, rel, detail, msg, line)
        for i, n in sorted(scan.ids.items()):
            if n > 1:
                add("ERROR", "a11y-dup-id", rel, i, f'id="{i}" appears {n} times in the markup')
        for line, tag, cid, nm in scan.controls:
            if cid and cid in scan.label_for:
                continue
            add("ERROR", "a11y-input-label", rel, cid or f"line {line}", f"<{tag}{' id=' + cid if cid else ''}{' ' + nm if nm else ''}> has no label, aria-label or title", line)
        for m in re.finditer(r"""<(?:script|link)\b[^>]*\b(?:src|href)\s*=\s*["'][^"']*assets/vendor/""", text):
            add("ERROR", "vendor-eager", rel, "-", "loads assets/vendor/ eagerly: load it from the code that needs it, when it is needed", text.count("\n", 0, m.start()) + 1)
    for rel in (f for f in files if f.startswith("assets/js/") and f.endswith(".js")):
        try:
            js = (root / rel).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for m in re.finditer(r"""^\s*(?:import|export)\b[^;\n]*?\bfrom\s*["'][^"']*vendor/""", js, re.M):
            add("ERROR", "vendor-eager", rel, "-", "imports a vendored library statically: use import() or inject the script when it is needed", js.count("\n", 0, m.start()) + 1)


def run_checks(root=ROOT, allow=None, deep=False, max_size_kb=DEFAULT_MAX_SIZE_KB, page_kb=PAGE_BUDGET_KB, chapter_kb=CHAPTER_BUDGET_KB, max_page_kb=MAX_PAGE_KB):
    """Runs every check on the site under `root`. `allow` is a list from load_allow()."""
    root = Path(root)
    allow = allow or []
    files, dirs = walk_site(root)
    lower = {}
    for f in files:
        lower.setdefault(f.lower(), []).append(f)
    raw_findings = []
    report = Report()

    def add(level, code, file, detail, message, line=None):
        raw_findings.append(Finding(level, code, file, detail, message, line))

    # ---- scan pages -------------------------------------------------------
    html_files = sorted(f for f in files if f.endswith(".html"))
    scans, titles = {}, {}
    for rel in html_files:
        if not in_scope(rel, deep):
            report.stats["skipped"] += 1
            continue
        try:
            text = (root / rel).read_bytes().decode("utf-8-sig")
        except (OSError, UnicodeDecodeError) as e:
            add("ERROR", "read-error", rel, "-", f"cannot read as UTF-8: {e}")
            continue
        scan = PageScan()
        scan.feed(text)
        scan.close()
        scan.ids |= set(ID_RE.findall(text))
        scans[rel] = scan
        report.stats["pages"] += 1

    ids_cache = {}
    dyn_anchors = dynamic_anchors(root, files)

    def ids_of(rel):
        if rel in scans:
            return scans[rel].ids
        if rel not in ids_cache:
            try:
                ids_cache[rel] = set(ID_RE.findall((root / rel).read_text(encoding="utf-8", errors="replace")))
            except OSError:
                ids_cache[rel] = set()
        return ids_cache[rel]

    # ---- links and anchors --------------------------------------------------
    for rel, scan in scans.items():
        seen = {}
        for url, line, what in scan.refs:
            seen.setdefault(url, [line, what, 0])[2] += 1
        for url, (line, what, count) in seen.items():
            ref = split_ref(rel, url)
            if ref is None:
                continue
            report.stats["links"] += count
            target, frag, same_page = ref
            times = f" (x{count})" if count > 1 else ""
            if target in ("", "."):
                target = "index.html"
            is_dir_link = target.endswith("/") or (target in dirs and target not in files)
            resolved = target.rstrip("/")
            if is_dir_link:
                resolved = f"{resolved}/index.html" if resolved else "index.html"
            if resolved not in files:
                hint = ""
                near = lower.get(resolved.lower(), [])
                if near:
                    hint = f" (case differs: the file is {near[0]})"
                elif is_dir_link:
                    hint = " (directory has no index.html)"
                add("ERROR", "broken-link", rel, url, f'{what}="{url}" -> not found{hint}{times}', line)
                continue
            if frag and not frag.startswith(("/", "!")) and frag.lower() != "top" and resolved.endswith(".html"):
                if frag not in ids_of(resolved) and frag not in dyn_anchors.get(resolved, ()):
                    add("ERROR", "broken-anchor", rel, url, f'{what}="{url}" -> no id "{frag}" in {resolved}{times}', line)

    # ---- titles -------------------------------------------------------------
    for rel, scan in scans.items():
        title = " ".join(scan.title.split())
        if not title:
            add("ERROR", "no-title", rel, "-", "page has no <title>" if not scan.has_title else "<title> is empty")
            continue
        parts = [p.strip().casefold() for p in TITLE_SEPARATORS.split(title) if p.strip()]
        if len(parts) != len(set(parts)):
            add("ERROR", "dup-title-part", rel, title, f'title repeats itself: "{title}"')
        titles.setdefault(title, []).append(rel)
    for title, pages in sorted(titles.items()):
        if len(pages) > 1:
            add("WARN", "dup-title", pages[0], title, f'same title on {len(pages)} pages ({", ".join(pages)}): "{title}"')

    # ---- JSON ---------------------------------------------------------------
    for rel in sorted(f for f in files if f.endswith(".json")):
        report.stats["json"] += 1
        try:
            json.loads((root / rel).read_bytes().decode("utf-8-sig"))
        except (ValueError, UnicodeDecodeError) as e:
            add("ERROR", "bad-json", rel, "-", f"does not parse: {e}")

    # ---- size budget --------------------------------------------------------
    for rel in sorted(files):
        if rel.startswith(VENDOR_DIR):
            continue                         # vendored libraries (Mermaid is ~3.5 MB) are not ours to slim down
        size = (root / rel).stat().st_size
        if size > max_size_kb * 1024:
            add("WARN", "big-file", rel, "-", f"{size // 1024} KB (budget {max_size_kb} KB)")

    # ---- budgets, lazy vendors, accessibility of the markup (P23) ----------
    check_quality(root, files, set(scans), add, page_kb, chapter_kb, max_page_kb)

    # ---- navigation (only once P02 has created it) --------------------------
    nav_file = root / NAV_PATH
    if nav_file.is_file():
        try:
            nav = json.loads(nav_file.read_bytes().decode("utf-8-sig"))
        except ValueError:
            nav = None                       # already reported as bad-json
        if nav is not None:
            urls = set()

            def collect(node):
                if isinstance(node, dict):
                    if isinstance(node.get("url"), str):
                        urls.add(node["url"])
                    for v in node.values():
                        collect(v)
                elif isinstance(node, list):
                    for v in node:
                        collect(v)
            collect(nav)
            listed = set()
            for u in sorted(urls):
                ref = split_ref(NAV_PATH, u if u.startswith("/") else "/" + u)
                if ref is None:
                    continue
                target = ref[0].rstrip("/") or "index.html"
                listed.add(target)
                if target not in files and f"{target}/index.html" not in files:
                    add("ERROR", "nav-dead-url", NAV_PATH, u, f'nav url "{u}" does not exist')
            for rel in html_files:
                if "/" not in rel and rel not in NAV_EXEMPT and rel not in listed:
                    add("ERROR", "not-in-nav", rel, "-", f"{rel} is not listed in {NAV_PATH}")

    # ---- glossary and reading paths (P05) -----------------------------------
    check_content_refs(root, files, ids_of, add)

    # ---- figures (P06) ------------------------------------------------------
    check_figures(root, files, ids_of, add)

    # ---- architecture model (P25) -------------------------------------------
    check_arch(root, files, ids_of, add)
    check_arch_legacy(root, files, add)

    # ---- allow list ---------------------------------------------------------
    used = set()
    for f in raw_findings:
        hit = next((raw for raw, rx in allow if rx.match(f.key)), None)
        if hit:
            used.add(hit)
            report.allowed.append(f)
        else:
            report.findings.append(f)
    for raw, _ in allow:
        if raw not in used:
            report.findings.append(Finding("WARN", "unused-allow", "scripts/check_site.allow", raw, f"allow line matched nothing: {raw}"))
    report.findings.sort(key=lambda f: (f.level != "ERROR", f.file, f.line or 0, f.code))
    return report


def main(argv=None):
    ap = argparse.ArgumentParser(description="Find broken links, anchors, titles, JSON and oversize files in the Atlas.")
    ap.add_argument("--root", default=str(ROOT), help="site root (default: this repo)")
    ap.add_argument("--allow", default=str(DEFAULT_ALLOW), help="allow-list file (default: scripts/check_site.allow)")
    ap.add_argument("--no-allow", action="store_true", help="ignore the allow list")
    ap.add_argument("--strict", action="store_true", help="warnings also fail")
    ap.add_argument("--deep", action="store_true", help="also read architecture/*.html")
    ap.add_argument("--max-size-kb", type=int, default=DEFAULT_MAX_SIZE_KB, help="size budget per file (warning)")
    ap.add_argument("--page-kb", type=int, default=PAGE_BUDGET_KB, help="HTML budget for a page that is not a chapter (error)")
    ap.add_argument("--chapter-kb", type=int, default=CHAPTER_BUDGET_KB, help="HTML budget for a chapter, doc-*.html (warning)")
    ap.add_argument("--max-page-kb", type=int, default=MAX_PAGE_KB, help="no HTML file over this (error)")
    ap.add_argument("--write-allow", action="store_true", help="print an allow line for every current error, then exit 0")
    args = ap.parse_args(argv)

    allow = [] if args.no_allow else load_allow(args.allow)
    report = run_checks(args.root, allow=allow, deep=args.deep, max_size_kb=args.max_size_kb, page_kb=args.page_kb, chapter_kb=args.chapter_kb, max_page_kb=args.max_page_kb)

    if args.write_allow:
        for f in report.errors:
            print(f"{f.key:<70} # TODO: why this is allowed, and which patch removes it")
        return 0

    for f in report.findings:
        print(f)
    s = report.stats
    print(f"\ncheck_site: {s['pages']} pages read ({s['skipped']} skipped), {s['links']} links, {s['json']} JSON files -> "
          f"{len(report.errors)} errors, {len(report.warnings)} warnings, {len(report.allowed)} allowed")
    code = report.exit_code(args.strict)
    if code:
        print("FAILED" + (" (strict: warnings count)" if args.strict and not report.errors else ""))
    return code


if __name__ == "__main__":
    sys.exit(main())
