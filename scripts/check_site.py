#!/usr/bin/env python3
"""
check_site.py -- find breakage in the Atlas before it is deployed. Standard library only.

    python scripts/check_site.py                  # check the repo, print findings, exit 1 on errors
    python scripts/check_site.py --strict         # warnings fail too
    python scripts/check_site.py --deep           # also read architecture/*.html (generated by archify)
    python scripts/check_site.py --write-allow    # print allow-list lines for every current error

Errors (exit 1)
    broken-link      a relative href/src whose file does not exist (case-exact, like Vercel on Linux)
    broken-anchor    page.html#id where page.html has no such id
    bad-json         a *.json file that does not parse
    no-title         a page without a <title>, or an empty one
    dup-title-part   a title that repeats itself, e.g. "MiniMe Atlas - MiniMe Atlas"
    not-in-nav       (only once content/nav.json exists) a root page that the nav does not list
    nav-dead-url     a nav.json url that does not resolve to a file
    read-error       a file that cannot be read as UTF-8

Warnings (exit 0, unless --strict)
    big-file         over the size budget (--max-size-kb, default 600)
    dup-title        two pages share exactly the same <title>
    unused-allow     an allow-list line that matched nothing (delete it)

Known issues go in scripts/check_site.allow, one per line:

    <code>|<file>|<detail>      # why this is allowed and which patch removes it

`*` is the only wildcard. Run --write-allow to get the exact keys.

What is read: pages in the site root and guides/. architecture/*.html (archify output) only with --deep; HTML
elsewhere (generator templates in scripts/) is input, not a page. Content inside <script> and <style> is never
scanned for links, so data baked into the big generated pages cannot cause false alarms. An id counts as present
if it is in the markup or inside a JavaScript string (id=\\"x\\"). Fragments that start with "/" or "!" are
client-side routes and are not checked.
"""
import argparse
import json
import os
import posixpath
import re
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

sys.dont_write_bytecode = True      # the repo tracks scripts/__pycache__; do not make it show as modified

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ALLOW = ROOT / "scripts" / "check_site.allow"
DEFAULT_MAX_SIZE_KB = 600
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".vercel", ".venv", "venv"}
PAGE_DIRS = ("guides/",)                          # besides the root: the folders whose pages are read
DEEP_DIRS = ("architecture/",)                    # generated by archify; read only with --deep
NAV_PATH = "content/nav.json"
NAV_EXEMPT = {"404.html"}                         # root pages that are not part of the navigation
LINK_ATTRS = {                                    # tag -> attributes that point at another file
    "a": ("href",), "link": ("href",), "script": ("src",), "img": ("src",), "iframe": ("src",),
    "source": ("src",), "video": ("src", "poster"), "audio": ("src",), "embed": ("src",),
}
EXTERNAL = re.compile(r"^(?:[a-zA-Z][a-zA-Z0-9+.\-]*:|//)")
DYNAMIC = re.compile(r"\$\{|\{\{|<%")
TITLE_SEPARATORS = re.compile(r"\s+[-\u2013\u2014\u00b7|]\s+")
# Also matches ids written inside JavaScript strings, e.g. id=\"doc-rulebook\" (journey.html builds its page that way).
ID_RE = re.compile(r"""\bid\s*=\s*\\*["']([^"'\\\s]+)""")


class Finding:
    def __init__(self, level, code, file, detail, message, line=None):
        self.level, self.code, self.file, self.detail, self.message, self.line = level, code, file, detail, message, line

    @property
    def key(self):
        return f"{self.code}|{self.file}|{self.detail}"

    def __str__(self):
        where = f"{self.file}:{self.line}" if self.line else self.file
        return f"{self.level:<5}  {self.code:<14} {where}  {self.message}"


class Report:
    def __init__(self):
        self.findings = []          # not allowed
        self.allowed = []           # matched an allow line
        self.stats = {"pages": 0, "skipped": 0, "links": 0, "json": 0}

    @property
    def errors(self):
        return [f for f in self.findings if f.level == "ERROR"]

    @property
    def warnings(self):
        return [f for f in self.findings if f.level == "WARN"]

    def exit_code(self, strict=False):
        return 1 if self.errors or (strict and self.warnings) else 0


class PageScan(HTMLParser):
    """Collects the <title>, every id and every file reference of one page."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.title, self.has_title = "", False
        self.ids = set()
        self.refs = []                  # (url, line, 'tag attr')
        self._in_title = False
        self._svg_depth = 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "svg":
            self._svg_depth += 1
        if tag == "title" and self._svg_depth == 0 and not self.has_title:
            self.has_title, self._in_title = True, True
        if a.get("id"):
            self.ids.add(a["id"])
        if tag == "a" and a.get("name"):
            self.ids.add(a["name"])
        for attr in LINK_ATTRS.get(tag, ()):
            if a.get(attr) is not None:
                self.refs.append((a[attr], self.getpos()[0], f"{tag} {attr}"))

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag == "svg":
            self._svg_depth -= 1

    def handle_endtag(self, tag):
        if tag == "svg" and self._svg_depth:
            self._svg_depth -= 1
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data


def glob_to_regex(pattern):
    return re.compile("^" + ".*".join(re.escape(p) for p in pattern.split("*")) + "$", re.S)


def load_allow(path):
    """Returns [(raw_line, regex)] from an allow file; missing file means no allowances."""
    rules = []
    if path and Path(path).is_file():
        for raw in Path(path).read_text(encoding="utf-8").splitlines():
            key = raw.split(" #", 1)[0].strip() if " #" in raw else raw.strip()
            if not key or key.startswith("#"):
                continue
            rules.append((key, glob_to_regex(key)))
    return rules


def walk_site(root):
    files, dirs = set(), set()
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        if rel_dir != ".":
            dirs.add(rel_dir)
        for name in filenames:
            files.add(name if rel_dir == "." else f"{rel_dir}/{name}")
    return files, dirs


def in_scope(rel, deep):
    """Pages whose content is checked: root, guides/, and architecture/ only with --deep.
    Other HTML (generator templates under scripts/, for example) is input, not a page."""
    return "/" not in rel or rel.startswith(PAGE_DIRS) or (deep and rel.startswith(DEEP_DIRS))


def split_ref(page, raw):
    """(target_path, fragment, same_page) for a relative reference, or None if it is not a site file."""
    raw = raw.strip()
    if not raw or EXTERNAL.match(raw) or DYNAMIC.search(raw):
        return None
    parts = urlsplit(raw)
    path, frag = unquote(parts.path), unquote(parts.fragment)
    if not path:
        return (page, frag, True) if frag else None
    if path.startswith("/"):
        target = posixpath.normpath(path.lstrip("/")) if path.strip("/") else ""
    else:
        target = posixpath.normpath(posixpath.join(posixpath.dirname(page), path))
    if path.endswith("/") and target not in ("", "."):
        target += "/"
    return target, frag, False


def run_checks(root=ROOT, allow=None, deep=False, max_size_kb=DEFAULT_MAX_SIZE_KB):
    """Runs every check on the site under `root`. `allow` is a list from load_allow()."""
    root = Path(root)
    allow = allow or []
    files, dirs = walk_site(root)
    lower = {}
    for f in files:
        lower.setdefault(f.lower(), []).append(f)
    raw_findings = []
    report = Report()

    def add(level, code, file, detail, message, line=None):
        raw_findings.append(Finding(level, code, file, detail, message, line))

    # ---- scan pages -------------------------------------------------------
    html_files = sorted(f for f in files if f.endswith(".html"))
    scans, titles = {}, {}
    for rel in html_files:
        if not in_scope(rel, deep):
            report.stats["skipped"] += 1
            continue
        try:
            text = (root / rel).read_bytes().decode("utf-8-sig")
        except (OSError, UnicodeDecodeError) as e:
            add("ERROR", "read-error", rel, "-", f"cannot read as UTF-8: {e}")
            continue
        scan = PageScan()
        scan.feed(text)
        scan.close()
        scan.ids |= set(ID_RE.findall(text))
        scans[rel] = scan
        report.stats["pages"] += 1

    ids_cache = {}

    def ids_of(rel):
        if rel in scans:
            return scans[rel].ids
        if rel not in ids_cache:
            try:
                ids_cache[rel] = set(ID_RE.findall((root / rel).read_text(encoding="utf-8", errors="replace")))
            except OSError:
                ids_cache[rel] = set()
        return ids_cache[rel]

    # ---- links and anchors --------------------------------------------------
    for rel, scan in scans.items():
        seen = {}
        for url, line, what in scan.refs:
            seen.setdefault(url, [line, what, 0])[2] += 1
        for url, (line, what, count) in seen.items():
            ref = split_ref(rel, url)
            if ref is None:
                continue
            report.stats["links"] += count
            target, frag, same_page = ref
            times = f" (x{count})" if count > 1 else ""
            if target in ("", "."):
                target = "index.html"
            is_dir_link = target.endswith("/") or (target in dirs and target not in files)
            resolved = target.rstrip("/")
            if is_dir_link:
                resolved = f"{resolved}/index.html" if resolved else "index.html"
            if resolved not in files:
                hint = ""
                near = lower.get(resolved.lower(), [])
                if near:
                    hint = f" (case differs: the file is {near[0]})"
                elif is_dir_link:
                    hint = " (directory has no index.html)"
                add("ERROR", "broken-link", rel, url, f'{what}="{url}" -> not found{hint}{times}', line)
                continue
            if frag and not frag.startswith(("/", "!")) and frag.lower() != "top" and resolved.endswith(".html"):
                if frag not in ids_of(resolved):
                    add("ERROR", "broken-anchor", rel, url, f'{what}="{url}" -> no id "{frag}" in {resolved}{times}', line)

    # ---- titles -------------------------------------------------------------
    for rel, scan in scans.items():
        title = " ".join(scan.title.split())
        if not title:
            add("ERROR", "no-title", rel, "-", "page has no <title>" if not scan.has_title else "<title> is empty")
            continue
        parts = [p.strip().casefold() for p in TITLE_SEPARATORS.split(title) if p.strip()]
        if len(parts) != len(set(parts)):
            add("ERROR", "dup-title-part", rel, title, f'title repeats itself: "{title}"')
        titles.setdefault(title, []).append(rel)
    for title, pages in sorted(titles.items()):
        if len(pages) > 1:
            add("WARN", "dup-title", pages[0], title, f'same title on {len(pages)} pages ({", ".join(pages)}): "{title}"')

    # ---- JSON ---------------------------------------------------------------
    for rel in sorted(f for f in files if f.endswith(".json")):
        report.stats["json"] += 1
        try:
            json.loads((root / rel).read_bytes().decode("utf-8-sig"))
        except (ValueError, UnicodeDecodeError) as e:
            add("ERROR", "bad-json", rel, "-", f"does not parse: {e}")

    # ---- size budget --------------------------------------------------------
    for rel in sorted(files):
        size = (root / rel).stat().st_size
        if size > max_size_kb * 1024:
            add("WARN", "big-file", rel, "-", f"{size // 1024} KB (budget {max_size_kb} KB)")

    # ---- navigation (only once P02 has created it) --------------------------
    nav_file = root / NAV_PATH
    if nav_file.is_file():
        try:
            nav = json.loads(nav_file.read_bytes().decode("utf-8-sig"))
        except ValueError:
            nav = None                       # already reported as bad-json
        if nav is not None:
            urls = set()

            def collect(node):
                if isinstance(node, dict):
                    if isinstance(node.get("url"), str):
                        urls.add(node["url"])
                    for v in node.values():
                        collect(v)
                elif isinstance(node, list):
                    for v in node:
                        collect(v)
            collect(nav)
            listed = set()
            for u in sorted(urls):
                ref = split_ref(NAV_PATH, u if u.startswith("/") else "/" + u)
                if ref is None:
                    continue
                target = ref[0].rstrip("/") or "index.html"
                listed.add(target)
                if target not in files and f"{target}/index.html" not in files:
                    add("ERROR", "nav-dead-url", NAV_PATH, u, f'nav url "{u}" does not exist')
            for rel in html_files:
                if "/" not in rel and rel not in NAV_EXEMPT and rel not in listed:
                    add("ERROR", "not-in-nav", rel, "-", f"{rel} is not listed in {NAV_PATH}")

    # ---- allow list ---------------------------------------------------------
    used = set()
    for f in raw_findings:
        hit = next((raw for raw, rx in allow if rx.match(f.key)), None)
        if hit:
            used.add(hit)
            report.allowed.append(f)
        else:
            report.findings.append(f)
    for raw, _ in allow:
        if raw not in used:
            report.findings.append(Finding("WARN", "unused-allow", "scripts/check_site.allow", raw, f"allow line matched nothing: {raw}"))
    report.findings.sort(key=lambda f: (f.level != "ERROR", f.file, f.line or 0, f.code))
    return report


def main(argv=None):
    ap = argparse.ArgumentParser(description="Find broken links, anchors, titles, JSON and oversize files in the Atlas.")
    ap.add_argument("--root", default=str(ROOT), help="site root (default: this repo)")
    ap.add_argument("--allow", default=str(DEFAULT_ALLOW), help="allow-list file (default: scripts/check_site.allow)")
    ap.add_argument("--no-allow", action="store_true", help="ignore the allow list")
    ap.add_argument("--strict", action="store_true", help="warnings also fail")
    ap.add_argument("--deep", action="store_true", help="also read architecture/*.html")
    ap.add_argument("--max-size-kb", type=int, default=DEFAULT_MAX_SIZE_KB, help="size budget per file (warning)")
    ap.add_argument("--write-allow", action="store_true", help="print an allow line for every current error, then exit 0")
    args = ap.parse_args(argv)

    allow = [] if args.no_allow else load_allow(args.allow)
    report = run_checks(args.root, allow=allow, deep=args.deep, max_size_kb=args.max_size_kb)

    if args.write_allow:
        for f in report.errors:
            print(f"{f.key:<70} # TODO: why this is allowed, and which patch removes it")
        return 0

    for f in report.findings:
        print(f)
    s = report.stats
    print(f"\ncheck_site: {s['pages']} pages read ({s['skipped']} skipped), {s['links']} links, {s['json']} JSON files -> "
          f"{len(report.errors)} errors, {len(report.warnings)} warnings, {len(report.allowed)} allowed")
    code = report.exit_code(args.strict)
    if code:
        print("FAILED" + (" (strict: warnings count)" if args.strict and not report.errors else ""))
    return code


if __name__ == "__main__":
    sys.exit(main())
